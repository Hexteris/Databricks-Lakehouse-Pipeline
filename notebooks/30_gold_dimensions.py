# MAGIC %md
# MAGIC ## dim_client: SCD Type 2
# MAGIC
# MAGIC A client's **circumstances** are history the business cares about. If a client moves from Bedok to Tampines,
# MAGIC referrals made while they lived in Bedok should still count for Bedok. So those columns keep history:
# MAGIC
# MAGIC | Column type | Columns | On change |
# MAGIC |---|---|---|
# MAGIC | **Type 2** (history) | planning_area, household_type, postal_code | close the current row, add a new version |
# MAGIC | **Type 1** (overwrite) | name, NRIC hash/mask, phone, email | update the current row in place |
# MAGIC
# MAGIC Each version has `effective_from` and `effective_to`, read as **from (inclusive) up to (not inclusive)**.
# MAGIC The current version has `effective_to = 9999-12-31` and `is_current = true`.
# MAGIC A client's first version starts at `1900-01-01`, so referrals from before the first load still find a version.
# MAGIC
# MAGIC Two fingerprints decide what to do:
# MAGIC - `scd_hash`: the Type 2 columns only. Different means **new version**.
# MAGIC - `row_hash` (from silver): every column. Different, with `scd_hash` the same, means a **Type 1 update**.

# COMMAND ----------

spark.sql(f"""
CREATE TABLE IF NOT EXISTS {CATALOG}.gold.dim_client (
    client_sk         BIGINT GENERATED ALWAYS AS IDENTITY,
    client_id         STRING,
    full_name         STRING,
    nric_hash         STRING,
    nric_masked       STRING,
    phone_enc         STRING,
    email_enc         STRING,
    planning_area     STRING,
    household_type    STRING,
    postal_code       STRING,
    scd_hash          STRING   COMMENT 'Fingerprint of the Type 2 columns',
    row_hash          STRING   COMMENT 'Fingerprint of all columns, from silver',
    effective_from    DATE,
    effective_to      DATE     COMMENT 'Not inclusive. 9999-12-31 for the current version',
    is_current        BOOLEAN,
    _gold_run_id      STRING,
    _gold_updated_at  TIMESTAMP
)""")

spark.sql(f"""
CREATE OR REPLACE TEMP VIEW client_source AS
SELECT *, sha2(concat_ws('|', planning_area, household_type, postal_code), 256) AS scd_hash
FROM {CATALOG}.silver.slv_clients
""")

# COMMAND ----------

# MAGIC %md
# MAGIC ### Preview: what will this run change?
# MAGIC Counted before the MERGE, so the log can say exactly how many new versions and in-place updates there were.

# COMMAND ----------

preview = spark.sql(f"""
SELECT
    count_if(t.client_id IS NULL)                                         AS new_clients,
    count_if(t.client_id IS NOT NULL AND t.scd_hash <> s.scd_hash)        AS new_versions,
    count_if(t.client_id IS NOT NULL AND t.scd_hash = s.scd_hash
             AND t.row_hash <> s.row_hash)                                AS type1_updates
FROM client_source s
LEFT JOIN {CATALOG}.gold.dim_client t ON t.client_id = s.client_id AND t.is_current
""").first()
print(preview)

# COMMAND ----------

# MAGIC %md
# MAGIC ### The SCD2 MERGE
# MAGIC A single MERGE can't both close the old row **and** insert the new version for the same client,
# MAGIC because each source row produces only one action. So the source lists changed clients **twice**:
# MAGIC
# MAGIC 1. With `merge_key = client_id`: matches the current row, which is then closed (or Type 1 updated).
# MAGIC 2. With `merge_key = NULL`: can never match, so it's inserted as the new version.
# MAGIC
# MAGIC Doing it all in one MERGE means it's one transaction: no moment where a client has zero or two current rows.

# COMMAND ----------

target = f"{CATALOG}.gold.dim_client"
log_start("gold", target)
try:
    m = spark.sql(f"""
    MERGE INTO {target} t
    USING (
        SELECT s.client_id AS merge_key, s.* FROM client_source s
        UNION ALL
        SELECT NULL AS merge_key, s.*
        FROM client_source s
        JOIN {target} d ON d.client_id = s.client_id AND d.is_current AND d.scd_hash <> s.scd_hash
    ) s
    ON t.client_id = s.merge_key AND t.is_current

    -- Type 2 change: close the current version on the day the change happened
    WHEN MATCHED AND t.scd_hash <> s.scd_hash THEN UPDATE SET
        effective_to = s.updated_date, is_current = false,
        _gold_run_id = '{RUN_ID}', _gold_updated_at = current_timestamp()

    -- Type 1 change only: overwrite the current version in place
    WHEN MATCHED AND t.row_hash <> s.row_hash THEN UPDATE SET
        full_name = s.full_name, nric_hash = s.nric_hash, nric_masked = s.nric_masked,
        phone_enc = s.phone_enc, email_enc = s.email_enc, row_hash = s.row_hash,
        _gold_run_id = '{RUN_ID}', _gold_updated_at = current_timestamp()

    -- New client (first version from 1900), or new version of a changed client (from the change date)
    WHEN NOT MATCHED THEN INSERT
        (client_id, full_name, nric_hash, nric_masked, phone_enc, email_enc, planning_area, household_type,
         postal_code, scd_hash, row_hash, effective_from, effective_to, is_current, _gold_run_id, _gold_updated_at)
    VALUES
        (s.client_id, s.full_name, s.nric_hash, s.nric_masked, s.phone_enc, s.email_enc, s.planning_area,
         s.household_type, s.postal_code, s.scd_hash, s.row_hash,
         CASE WHEN s.merge_key IS NULL THEN s.updated_date ELSE DATE'1900-01-01' END,
         DATE'9999-12-31', true, '{RUN_ID}', current_timestamp())
    """).first()

    note = (f"new_clients={preview.new_clients} new_versions={preview.new_versions} "
            f"type1_updates={preview.type1_updates} | merge inserted={m.num_inserted_rows} updated={m.num_updated_rows}")
    rows_out = spark.table(target).count()
    log_end(target, "SUCCESS", rows_in=spark.table("client_source").count(), rows_out=rows_out, note=note)
    print(f"{target}: rows={rows_out} | {note}")
except Exception as e:
    log_end(target, "FAILED", error_msg=str(e)[:1000])
    raise

