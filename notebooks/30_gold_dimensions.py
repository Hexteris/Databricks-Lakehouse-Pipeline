# MAGIC %md
# MAGIC # 30_gold_dimensions
# MAGIC
# MAGIC Gold is a **star schema**: one fact table of referrals, surrounded by dimension tables that describe them.
# MAGIC This notebook builds the dimensions. `31_gold_facts` builds the fact.
# MAGIC
# MAGIC | Dimension | Describes | How changes are handled |
# MAGIC |---|---|---|
# MAGIC | `dim_date` | the referral date | generated once, never changes |
# MAGIC | `dim_programme` | what the client was referred to | **SCD Type 1**: overwrite, no history |
# MAGIC | `dim_location` | planning area, with real Census 2020 figures | **SCD Type 1** |
# MAGIC | `dim_client` | who was referred | **SCD Type 2**: keep a new row for each real change in circumstances |
# MAGIC
# MAGIC Every dimension has a **surrogate key** (`*_sk`): a number generated by the warehouse, separate from the source id.
# MAGIC SCD2 needs it, because one `client_id` can have several versions, and the fact must point to exactly one.
# MAGIC
# MAGIC *Programme and agency names are illustrative and do not represent real MSF schemes or data.*

# COMMAND ----------

# MAGIC %run ./00_common

# COMMAND ----------

def run_logged(target, source_table, sql):
    """Run one statement that builds a gold table, and log the outcome."""
    log_start("gold", target)
    try:
        result = spark.sql(sql).first()
        rows_in = spark.table(source_table).count() if source_table else None
        # A MERGE returns how many rows it inserted and updated. CREATE TABLE AS doesn't report updates.
        stats = result.asDict() if result is not None else {}
        note = (f"inserted={stats['num_inserted_rows']} updated={stats['num_updated_rows']}"
                if "num_updated_rows" in stats else None)
        rows_out = spark.table(target).count()
        log_end(target, "SUCCESS", rows_in=rows_in, rows_out=rows_out, note=note)
        print(f"{target}: rows={rows_out}" + (f" | {note}" if note else ""))
    except Exception as e:
        log_end(target, "FAILED", error_msg=str(e)[:1000])
        raise

