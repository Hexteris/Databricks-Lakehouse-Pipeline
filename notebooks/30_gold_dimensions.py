# MAGIC %md
# MAGIC ## dim_date
# MAGIC One row per day, 2020 to 2030. Reports can then group by month, quarter or weekday without date functions.
# MAGIC The key is the date as a number (20260315), which is easy to read and to join on.

# COMMAND ----------

run_logged(f"{CATALOG}.gold.dim_date", None, f"""
CREATE OR REPLACE TABLE {CATALOG}.gold.dim_date AS
SELECT
    CAST(date_format(d, 'yyyyMMdd') AS INT) AS date_sk,
    d                                       AS date,
    year(d)                                 AS year,
    quarter(d)                              AS quarter,
    month(d)                                AS month,
    date_format(d, 'MMMM')                  AS month_name,
    date_format(d, 'EEEE')                  AS day_name,
    dayofweek(d) IN (1, 7)                  AS is_weekend
FROM (SELECT explode(sequence(DATE'2020-01-01', DATE'2030-12-31', INTERVAL 1 DAY)) AS d)
""")

