# MAGIC %md
# MAGIC ## dim_programme and dim_location: SCD Type 1
# MAGIC If a programme is renamed, the old name simply isn't needed any more: overwrite it.
# MAGIC `<=>` is a null-safe equals, so a value changing to or from NULL also counts as a change.
# MAGIC The surrogate key is generated automatically on insert (`GENERATED ALWAYS AS IDENTITY`) and never changes.

# COMMAND ----------

spark.sql(f"""
CREATE TABLE IF NOT EXISTS {CATALOG}.gold.dim_programme (
    programme_sk      BIGINT GENERATED ALWAYS AS IDENTITY,
    programme_id      STRING,
    programme_name    STRING,
    agency_name       STRING,
    _gold_updated_at  TIMESTAMP
)""")

run_logged(f"{CATALOG}.gold.dim_programme", f"{CATALOG}.silver.slv_programmes", f"""
MERGE INTO {CATALOG}.gold.dim_programme t
USING {CATALOG}.silver.slv_programmes s
ON t.programme_id = s.programme_id
WHEN MATCHED AND NOT (t.programme_name <=> s.programme_name AND t.agency_name <=> s.agency_name) THEN
    UPDATE SET programme_name = s.programme_name, agency_name = s.agency_name, _gold_updated_at = current_timestamp()
WHEN NOT MATCHED THEN
    INSERT (programme_id, programme_name, agency_name, _gold_updated_at)
    VALUES (s.programme_id, s.programme_name, s.agency_name, current_timestamp())
""")

